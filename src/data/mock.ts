function pass(time: string, o2 = "20.9%", co = "0 ppm"): GasReading {
  return { time, o2, lel: "0%", co, result: "PASS" };
}

function signed(role: string, name: string, time: string): Signoff {
  return { role, name, state: "signed", time };
}

function waiting(role: string): Signoff {
  return { role, name: "", state: "outstanding", time: "" };
}

interface Seed {
  id: string;
  kind: PermitKind;
  status: PermitStatus;
  revision?: string;
  area: string;
  equipment?: string;
  location?: string;
  work: string;
  jobDescription?: string;
  workOrder: string;
  company: string;
  requester?: string;
  requesterGroup?: string;
  craft?: string;
  shiftSupervisor?: string;
  attendant?: string;
  entrants?: string[];
  fireWatch?: string;
  started?: string;
  expires?: string;
  issued?: string;
  closed?: string;
  issuedKey?: string;
  year?: number;
  isolation?: Permit["isolation"];
  readings?: GasReading[];
  hazards?: string[];
  ppe?: string[];
  precautions?: string[];
  attachments?: Attachment[];
  history?: TimelineEvent[];
  suspension?: Permit["suspension"];
  signoffs?: Signoff[];
  conditions?: Condition[];
  extraHistory?: TimelineEvent[];
}

function historyFrom(started: string): TimelineEvent[] {
  return [
    { time: shiftTime(started, -32), label: "CREATED", tone: "neutral" },
    { time: shiftTime(started, -16), label: "JSA VERIFIED", tone: "ok" },
    { time: shiftTime(started, -4), label: "AUTHORIZED - SHIFT SUPERVISOR", tone: "alert" },
    { time: started, label: "ACTIVE", tone: "alert" },
  ];
}

function build(seed: Seed): Permit {
  const confined = seed.kind === "confined-space";
  const digging = seed.kind === "excavation";
  const started = seed.started ?? "";
  const stamp = started || "08:00";
  return {
    id: seed.id,
    kind: seed.kind,
    status: seed.status,
    revision: seed.revision ?? "01",
    area: seed.area,
    equipment: seed.equipment ?? "",
    location: seed.location ?? "",
    work: seed.work,
    jobDescription: seed.jobDescription ?? seed.work,
    workOrder: seed.workOrder,
    company: seed.company,
    companyType: seed.company === "LCY" ? "LCY" : "Contractor",
    requester: seed.requester ?? "Elena Voss",
    requesterGroup: seed.requesterGroup ?? "Maintenance",
    craft: seed.craft ?? "Jordan Peck",
    shiftSupervisor: seed.shiftSupervisor ?? "Marcus Hale",
    attendant: seed.attendant ?? (confined ? "Chris Daley" : ""),
    entrants: seed.entrants ?? (confined ? ["Ana Ruiz"] : []),
    fireWatch: seed.fireWatch ?? "",
    started,
    expires: seed.expires ?? "",
    issued: seed.issued ?? "21 Oct 2026",
    closed: seed.closed ?? "",
    issuedKey: seed.issuedKey ?? "20261021",
    year: seed.year ?? 2026,
    isolation: seed.isolation ?? {
      required: confined ? "Yes" : "No",
      plan: confined ? "ECP-2814" : "—",
      lockBox: confined ? "LB-018" : "—",
      zeroEnergy: confined ? "Verified this shift" : "—",
      blinds: confined ? "Yes" : "—",
    },
    readings: seed.readings ?? (confined ? [pass(started ? shiftTime(started, 8) : stamp)] : []),
    hazards:
      seed.hazards ??
      (confined
        ? ["Atmospheric", "Stored energy", "Engulfment"]
        : digging
          ? ["Excavation/cave-in", "Underground utilities", "Traffic"]
          : ["As stated on the JSA"]),
    ppe: seed.ppe ?? ["FR clothing", "Hard hat", "Safety glasses", "Gloves"],
    precautions:
      seed.precautions ??
      (confined
        ? ["JSA", "LOTO", "Ventilation", "Monitoring", "Attendant"]
        : digging
          ? ["JSA", "Barricades", "Locate ticket", "Protective system"]
          : ["JSA", "PPE"]),
    attachments: seed.attachments ?? [jsa],
    history: [...(seed.history ?? (started ? historyFrom(started) : [])), ...(seed.extraHistory ?? [])],
    suspension: seed.suspension ?? null,
    signoffs:
      seed.signoffs ?? [
        signed("Shift Supervisor", seed.shiftSupervisor ?? "Marcus Hale", stamp),
        signed("Requester", seed.requester ?? "Elena Voss", stamp),
        signed("Craft / Permit Receiver", seed.craft ?? "Jordan Peck", stamp),
      ],
    conditions:
      seed.conditions ??
      (confined
        ? [
            { label: "Continuous monitoring", value: "Yes" },
            { label: "Rescue availability", value: "Rescue team assigned to the unit" },
            { label: "Hot work controls", value: "No hot work authorized" },
          ]
        : digging
          ? [
              { label: "Expected depth", value: "4 ft" },
              { label: "Protective system", value: "Sloping" },
              { label: "Soil classification", value: "Type B" },
              { label: "One-call / locate ticket", value: "811-441902" },
            ]
          : []),
  };
}

